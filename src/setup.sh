#!/bin/bash
#
# Runs inside the container. `docker run --rm -e SETUP=true <image> | bash`
# prints a host bootstrap script on STDOUT and nothing else - every diagnostic
# must go to stderr, or it lands in the pipe and bash tries to execute it.

set -euo pipefail

IMAGE="${DEVCONTAINER_IMAGE:-bbartolome/tride:latest}"

echo "devcontainer: emitting bootstrap script for ${IMAGE}" >&2

# The image ref is injected line by line rather than through an unquoted
# heredoc, so nothing else in the script body can expand container-side.
printf '#!/usr/bin/env bash\n'
printf '# Generated by %s\n' "$IMAGE"
printf '# Re-run with: docker run --rm -e SETUP=true %s | bash\n' "$IMAGE"
printf 'set -euo pipefail\n'
printf 'IMAGE="%s"\n' "$IMAGE"

cat <<'BOOTSTRAP'

TARGET="$PWD"

die() { echo "devcontainer: $*" >&2; exit 1; }
note() { echo "devcontainer: $*" >&2; }

command -v docker >/dev/null 2>&1 \
  || die "docker is not installed or not on PATH"
docker compose version >/dev/null 2>&1 \
  || die "'docker compose' is unavailable - Compose v2 is required"

# This script arrives on stdin through the pipe, so stdin is NOT the terminal.
# Anything interactive has to go to /dev/tty explicitly.
have_tty=false
if (exec 3</dev/tty) 2>/dev/null; then
  have_tty=true
fi

existing=()
for f in Dockerfile docker-compose.yml wizard.sh .env .secret .sudopass; do
  [ -e "$TARGET/$f" ] && existing+=("$f")
done

if [ ${#existing[@]} -gt 0 ]; then
  if [ "$have_tty" = true ]; then
    note "these files already exist in $TARGET and may be overwritten:"
    printf '  - %s\n' "${existing[@]}" >&2
    printf 'devcontainer: continue? [y/N] ' >&2
    read -r reply < /dev/tty
    case "$reply" in
      [yY]|[yY][eE][sS]) ;;
      *) die "aborted - nothing was written" ;;
    esac
  else
    die "refusing to overwrite ${existing[*]} in $TARGET with no TTY to confirm"
  fi
fi

note "extracting installer files into $TARGET"
docker run --rm "$IMAGE" tar -cf - -C /opt/installer . | tar -xf - -C "$TARGET"

chmod +x "$TARGET/wizard.sh"

# The wizard writes this into .env so the compose build pins the same image
# this bootstrap came from.
export BASE_IMAGE="$IMAGE"

if [ "$have_tty" = true ]; then
  exec "$TARGET/wizard.sh" < /dev/tty
fi

note "installer files written to $TARGET"
note "no TTY available - run ./wizard.sh there to finish setup"
BOOTSTRAP
